PRODUCT_COPY_FILES += \\
EOF_MK

LINEEND=" \\"
COUNT=`egrep -vc '(^#|^$)' proprietary-files.txt`
for FILE in `egrep -v '(^#|^$)' proprietary-files.txt`; do
    COUNT=`expr $COUNT - 1`
    if [ $COUNT = "0" ]; then
        LINEEND=""
    fi
    OLDIFS=$IFS IFS=":" PARSING_ARRAY=($FILE) IFS=$OLDIFS
    FILE=`echo ${PARSING_ARRAY[0]} | sed -e "s/^-//g"`
    DEST=${PARSING_ARRAY[1]}
    if [ -z "$DEST" ]; then
        DEST=$FILE
    fi
    echo "	vendor/$VENDOR/$DEVICE/proprietary/$DEST:system/$DEST$LINEEND" >> $MAKEFILE
done
